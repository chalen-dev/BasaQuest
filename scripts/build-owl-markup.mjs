// File: scripts/build-owl-markup.mjs
//
// Regenerates src/components/ui/owlRig/owlMarkup.ts from the owl icon studio's
// HTML (owl-icon.html): the artwork of the full owl (<svg id="owlSvg">) and of the
// round portrait (<svg id="iconSvg">), turned into template functions that take a
// per-instance id prefix `p` so several owls can share a page.
//
//   node scripts/build-owl-markup.mjs path/to/owl-icon.html
//
// What it changes in the artwork: every id="x" becomes id="${p}x" data-r="x"
// (data-r is how owlEngine.ts finds the element), and every url(#x) / href="#x"
// points at the prefixed id. Nothing else is touched, no path data is retyped.
// The animation itself (the numbers and maths) lives in owlEngine.ts and is ported
// from the same HTML's <script> by hand.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const source = process.argv[2]
if (!source) {
    console.error('Usage: node scripts/build-owl-markup.mjs path/to/owl-icon.html')
    process.exit(1)
}
const html = readFileSync(source, 'utf8').replace(/\r\n/g, '\n')

// The inside of one <svg id="..."> element, without its opening tag and <title>.
function innerSvg(id) {
    const open = html.indexOf(`<svg id="${id}"`)
    if (open < 0) throw new Error(`No <svg id="${id}"> in ${source}`)
    const openEnd = html.indexOf('>', open) + 1
    const close = html.indexOf('</svg>', openEnd)
    let inner = html.slice(openEnd, close)
    inner = inner.replace(/^<title[^>]*>[\s\S]*?<\/title>/, '')
    return inner
}

function prefixed(inner) {
    if (inner.includes('`') || inner.includes('${')) throw new Error('Artwork contains a backtick or ${ - cannot embed in a template literal')
    return inner
        .replace(/\bid="([^"]+)"/g, (_, name) => `id="\${p}${name}" data-r="${name}"`)
        .replace(/url\(#([^)]+)\)/g, (_, name) => `url(#\${p}${name})`)
        .replace(/href="#([^"]+)"/g, (_, name) => `href="#\${p}${name}"`)
}

const full = prefixed(innerSvg('owlSvg'))
const portrait = prefixed(innerSvg('iconSvg'))

const out = `// File: src/components/ui/owlRig/owlMarkup.ts
//
// The owl's artwork as SVG markup, taken from the owl icon studio prototype
// (owl-icon.html) without retyping any path data. \`p\` is a per-instance prefix
// added to every id so several owls can share a page: gradients, clip paths and
// <use> references all point at their own copy. Each element the animation
// touches also carries data-r="<name>", which is how owlEngine.ts finds it.
// Generated by scripts/build-owl-markup.mjs; edit the artwork in the prototype
// and regenerate, not here.

/** The full-body owl. viewBox 0 0 1280 1320. */
export const owlFullMarkup = (p: string): string => \`${full}\`

/** The circular portrait. viewBox -110 -120 1220 1240. It reuses the full owl's
 *  head, body and wings through <use>, so the full markup must be in the page. */
export const owlPortraitMarkup = (p: string): string => \`${portrait}\`
`
const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/components/ui/owlRig/owlMarkup.ts')
writeFileSync(target, out)
console.log(`Wrote ${target} (${out.length} bytes)`)
